const US_STATE_CODES = new Set(Object.values(US_STATE_BY_NAME))

/** Normalize a US state name or code to a 2-letter postal abbreviation. */
export function normalizeUsState(raw: string): string {
  const trimmed = raw.trim()
  if (!trimmed) return ''
  const upper = trimmed.toUpperCase()
  if (trimmed.length === 2 && US_STATE_CODES.has(upper)) return upper
  return US_STATE_BY_NAME[trimmed.toLowerCase()] ?? upper.slice(0, 2)
}
